import { test, expect } from '@playwright/test';

test('Prompt 6 Console to API classroom walkthrough', async ({ page }, testInfo) => {
  await page.goto('/?presentation=1');
  await expect(page.locator('#console-test')).toBeEnabled();
  await page.waitForTimeout(1800);
  await page.locator('#configuration-lab').scrollIntoViewIfNeeded();
  await page.locator('#console-test').click();
  await expect(page.locator('#match-count')).toHaveText('5 / 5 fields match');
  await page.locator('#console-result').scrollIntoViewIfNeeded();
  await page.waitForTimeout(2300);
  await page.locator('#api-test').click();
  await expect(page.locator('#api-result .outcome')).toHaveText('Turn finished');
  await page.locator('#api-result').scrollIntoViewIfNeeded();
  await page.waitForTimeout(2500);
  await page.locator('#scenario').selectOption('tools');
  await expect(page.locator('#match-count')).toHaveText('4 / 5 fields match');
  await page.locator('#api-test').click();
  await expect(page.locator('#api-result .outcome')).toHaveText('Needs confirmation');
  await page.locator('#api-result details').click();
  await page.waitForTimeout(2800);
  await page.locator('#comparison').scrollIntoViewIfNeeded();
  await page.waitForTimeout(3500);
  await page.locator('#source-code').scrollIntoViewIfNeeded();
  await page.waitForTimeout(4500);
  await page.locator('#source').evaluate(element => { element.parentElement!.scrollTop = element.parentElement!.scrollHeight; });
  await page.waitForTimeout(3500);
  await page.locator('#scenario').selectOption('same');
  await page.locator('#strategy').selectOption('reuse');
  await expect(page.locator('#source')).not.toContainText('agents.create');
  await page.locator('#api-test').click();
  await page.locator('#source-code').scrollIntoViewIfNeeded();
  await page.locator('#source').evaluate(element => { element.parentElement!.scrollTop = 0; });
  await page.waitForTimeout(4500);
  await page.locator('[data-file="src/reproduce.ts"]').click();
  await expect(page.locator('#filename')).toHaveText('src/reproduce.ts');
  await page.waitForTimeout(4500);
  await page.screenshot({ path: testInfo.outputPath('highlighted-code.png'), fullPage: true });
});
