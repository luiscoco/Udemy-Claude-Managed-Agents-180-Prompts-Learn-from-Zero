import { test, expect } from '@playwright/test';

test('Prompt 7 declarative configuration classroom walkthrough', async ({ page }, testInfo) => {
  await page.goto('/?presentation=1');
  await expect(page.locator('#review')).toBeEnabled();
  await page.waitForTimeout(1600);
  await page.locator('#definitions').scrollIntoViewIfNeeded();
  await page.waitForTimeout(2400);
  await page.locator('[data-file="environment"]').click();
  await page.waitForTimeout(2400);
  await page.locator('#review').click();
  await expect(page.locator('#plan-summary')).toContainText('2 to create');
  await page.locator('#apply-plan').scrollIntoViewIfNeeded();
  await page.waitForTimeout(1800);
  await page.locator('#apply').click();
  await page.locator('#lockfile').scrollIntoViewIfNeeded();
  await page.waitForTimeout(2800);
  await page.locator('#revise').click();
  await page.locator('[data-file="agent"]').click();
  await page.waitForTimeout(2200);
  await page.locator('#review').click();
  await expect(page.locator('#plan-summary')).toContainText('1 to update');
  await page.locator('#apply-plan').scrollIntoViewIfNeeded();
  await page.waitForTimeout(2800);
  await page.locator('#apply').click();
  await page.locator('#lockfile').scrollIntoViewIfNeeded();
  await expect(page.locator('#continuity')).toContainText('version 2');
  await page.waitForTimeout(3200);
  await page.locator('#review').click();
  await expect(page.locator('#plan-summary')).toContainText('2 unchanged');
  await page.waitForTimeout(2400);
  await page.locator('#apply').click();
  await page.locator('#missing-lock').check();
  await page.locator('#review').click();
  await expect(page.locator('#plan-summary')).toContainText('2 to create');
  await page.waitForTimeout(2800);
  await page.locator('#lockfile').scrollIntoViewIfNeeded();
  await page.waitForTimeout(3500);
  await page.screenshot({ path: testInfo.outputPath('highlighted-lockfile.png'), fullPage: true });
});
