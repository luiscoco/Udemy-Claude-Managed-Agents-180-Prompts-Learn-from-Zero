// Serialize disk commits and publish an updated snapshot only after atomic rename.
export class SessionStore {
  private sessions = new Map<string, LessonSession>();
  private pending: Promise<unknown> = Promise.resolve();
  constructor(private file: string) {}
  async load() {
    try {
      const values = z.array(sessionSchema).parse(JSON.parse(await readFile(this.file, 'utf8')));
      this.sessions = new Map(values.map(value => [value.id, value]));
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    }
  }
  all() { return structuredClone([...this.sessions.values()]); }
  get(id: string) { const value = this.sessions.get(id); return value ? structuredClone(value) : undefined; }
  async change(id: string, transform: (current: LessonSession | undefined) => LessonSession) {
    const operation = this.pending.catch(() => {}).then(async () => {
      const next = new Map(this.sessions);
      const current = this.get(id);
      const updated = sessionSchema.parse(transform(current));
      next.set(id, updated);
      await mkdir(dirname(this.file), { recursive: true });
      await writeFile(this.file + '.tmp', JSON.stringify([...next.values()], null, 2), { mode: 0o600 });
      await rename(this.file + '.tmp', this.file);
      this.sessions = next;
      return structuredClone(updated);
    });
    this.pending = operation;
    return operation;
  }
}

