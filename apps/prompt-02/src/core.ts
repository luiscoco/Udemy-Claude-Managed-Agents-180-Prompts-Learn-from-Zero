export function event(type: string, source: LessonEvent['source'], text?: string, stopReason?: string): LessonEvent {
  return { id: `${source}_evt_${randomUUID()}`, type, time: new Date().toISOString(), source,
    ...(text !== undefined ? { text } : {}), ...(stopReason !== undefined ? { stopReason } : {}) };
}

