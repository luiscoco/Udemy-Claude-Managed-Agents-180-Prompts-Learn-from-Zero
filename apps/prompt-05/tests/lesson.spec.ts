import { test, expect } from '@playwright/test';

test('Prompt 5 first working agent classroom walkthrough', async ({ page }, testInfo) => {
  await page.goto('/?presentation=1');
  await expect(page.locator('#create-agent')).toBeEnabled();
  await page.waitForTimeout(1800);
  await page.locator('#agent-lab').scrollIntoViewIfNeeded();
  await page.locator('#create-agent').click();
  await expect(page.locator('#agent-progress')).toHaveText('ID saved');
  await page.waitForTimeout(1500);
  await page.locator('#create-environment').click();
  await expect(page.locator('#start-session')).toBeEnabled();
  await page.waitForTimeout(1500);
  await page.locator('#start-session').click();
  await expect(page.locator('#state-value')).toHaveText('accepted');
  await page.waitForTimeout(2500);
  await page.locator('#observe').click();
  await expect(page.locator('#state-value')).toHaveText('running');
  await page.waitForTimeout(1800);
  await page.locator('#observe').click();
  await expect(page.locator('.agent-message')).toContainText('2 + 2 = 4');
  await page.waitForTimeout(3000);
  await page.locator('[data-event]').filter({ hasText: 'agent.message' }).click();
  await page.locator('#events').scrollIntoViewIfNeeded();
  await page.waitForTimeout(3000);
  await page.locator('#saved-ids').scrollIntoViewIfNeeded();
  await page.waitForTimeout(3000);
  await page.locator('#source-code').scrollIntoViewIfNeeded();
  await expect(page.locator('#source .token.keyword').first()).toBeAttached();
  await page.waitForTimeout(5000);
  await page.locator('#source').evaluate(element => { element.parentElement!.scrollTop = 400; });
  await page.waitForTimeout(4500);
  await page.locator('#source').evaluate(element => { element.parentElement!.scrollTop = element.parentElement!.scrollHeight; });
  await page.waitForTimeout(4000);
  await page.locator('[data-file="src/storage.ts"]').click();
  await expect(page.locator('#filename')).toHaveText('src/storage.ts');
  await page.locator('#source').evaluate(element => { element.parentElement!.scrollTop = element.parentElement!.scrollHeight; });
  await page.waitForTimeout(4500);
  await page.screenshot({ path: testInfo.outputPath('highlighted-code.png'), fullPage: true });
  await page.reload();
  await page.locator('#agent-lab').scrollIntoViewIfNeeded();
  await expect(page.locator('.agent-message')).toContainText('2 + 2 = 4');
  await page.waitForTimeout(2000);
});
